/**
 * Every fixed word, in four languages: the template owns its words, so a translation can't drop a heading, a label or
 * the button's purpose. Plain language throughout: short sentences, what happened, what to do, by when.
 */
export const LOCALES = ["en", "de", "fr", "ar"] as const;
export type Locale = (typeof LOCALES)[number];
export const LANGUAGE: Record<Locale, string> = { en: "English", de: "Deutsch", fr: "Français", ar: "العربية" };
export const dirOf = (l: Locale) => (l === "ar" ? "rtl" : "ltr");

export const money = (n: number, currency: string, l: Locale) =>
  new Intl.NumberFormat(l === "ar" ? "ar-EG" : l, { style: "currency", currency }).format(n);
export const longDate = (iso: string, l: Locale) =>
  new Intl.DateTimeFormat(l === "ar" ? "ar-EG" : l, { weekday: "long", day: "numeric", month: "long", timeZone: "UTC" }).format(new Date(iso + "T12:00:00Z"));
export const fullDate = (iso: string, l: Locale) =>
  new Intl.DateTimeFormat(l === "ar" ? "ar-EG" : l, { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(iso + "T12:00:00Z"));

